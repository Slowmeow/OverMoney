/* Подключение к облаку.
 *
 * Здесь два значения из вашего проекта Supabase:
 * Project Settings → API — адрес проекта и публикуемый ключ.
 *
 * ПРО КЛЮЧИ, потому что перепутать их дорого.
 *
 * Ключ ниже — публикуемый (sb_publishable_… или, в старых проектах, anon).
 * Он публичный ПО ЗАМЫСЛУ и обязан лежать здесь, в коде страницы. Его видит
 * каждый, кто откроет приложение и посмотрит исходник; спрятать его в
 * приложении без сервера физически невозможно — любая попытка была бы
 * не защитой, а её изображением. И прятать нечего: сам по себе он не
 * открывает ни одной строки данных. Кто что может прочитать, решают правила
 * на стороне базы (supabase/schema.sql), а они спрашивают, кто вошёл,
 * а не какой ключ предъявлен. Без входа в аккаунт этот ключ бесполезен.
 *
 * Секретный ключ (sb_secret_… или service_role) — полная противоположность.
 * Он обходит все правила разом и открывает данные всех пользователей.
 * В код его класть нельзя никогда, ни в каком виде, ни «временно».
 * Ему место только на сервере, которого у этого приложения нет,
 * то есть здесь ему места нет вовсе.
 *
 * Пока значения не заполнены, приложение работает целиком локально:
 * без аккаунтов и без синхронизации. Ничего при этом не ломается.
 */
(function () {
  'use strict';

  const CONFIG = {
    // Project Settings → API → Project URL
    supabaseUrl: '',

    // Project Settings → API Keys → публикуемый ключ.
    // Публичный по замыслу: см. пояснение выше.
    supabasePublishableKey: 'sb_publishable_TUnT0ea6s0jbaAfWzVcNUw_--7iglFZ'
  };

  function configured() {
    return !!(CONFIG.supabaseUrl && CONFIG.supabasePublishableKey);
  }

  window.App = window.App || {};
  window.App.config = {
    get url() { return String(CONFIG.supabaseUrl || '').replace(/\/+$/, ''); },
    get anonKey() { return CONFIG.supabasePublishableKey; },
    configured: configured
  };
})();
